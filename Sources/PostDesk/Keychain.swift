import Foundation
import Security

/// API keys live in the login keychain, never in the desk file or UserDefaults.
enum Keychain {
    static let service = "com.austintaylor.postdesk"
    static let anthropic = "anthropic-api-key"
    static let xBearer = "x-bearer-token"

    static func read(_ account: String) -> String {
        let query: [String: Any] = [
            kSecClass as String: kSecClassGenericPassword,
            kSecAttrService as String: service,
            kSecAttrAccount as String: account,
            kSecReturnData as String: true,
            kSecMatchLimit as String: kSecMatchLimitOne,
        ]
        var item: CFTypeRef?
        guard SecItemCopyMatching(query as CFDictionary, &item) == errSecSuccess, let data = item as? Data else { return "" }
        return String(decoding: data, as: UTF8.self)
    }

    static func write(_ value: String, account: String) {
        let query: [String: Any] = [
            kSecClass as String: kSecClassGenericPassword,
            kSecAttrService as String: service,
            kSecAttrAccount as String: account,
        ]
        SecItemDelete(query as CFDictionary)
        let value = value.trimmingCharacters(in: .whitespacesAndNewlines)
        if account == anthropic { UserDefaults.standard.set(!value.isEmpty, forKey: "setup.hasKey") }
        guard !value.isEmpty else { return }
        var add = query
        add[kSecValueData as String] = Data(value.utf8)
        SecItemAdd(add as CFDictionary, nil)
    }
}
